// Generates src/lib/demoTools.js from the bridge's own tool definitions
// (blender_mcp_bridge/tools/, via get_mcp_tools()) so Studio's demo-mode catalog can
// never drift from the real one.
//
// demoTools.js was previously a 3400-line hand-maintained snapshot with a
// "refresh manually" note. Drift there is invisible and expensive: the
// schema drives the Add/Edit Command forms, so a stale entry silently
// mis-types an argument, and a mis-typed argument can reach Blender as a
// string that no-ops without failing (see the numeric-string dimensions
// trap). Generating it removes the whole class.
//
// Runs from `npm run dev`/`npm run build` via package.json pre* hooks, the
// same pattern as sync-community-sessions.mjs. Python is invoked only to
// dump the tool list as JSON — get_mcp_tools() is pure data with no Blender
// dependency, so this works in CI where no Blender exists.
//
// If Python or the source tree is unavailable, the existing demoTools.js is
// left untouched and the build continues with a warning rather than failing
// — a Studio-only checkout should still build.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, '..', '..');
const OUT_FILE = join(__dirname, '..', 'src', 'lib', 'demoTools.js');

const HEADER = `/**
 * AUTO-GENERATED by studio/scripts/gen-demo-tools.mjs -- DO NOT EDIT BY HAND.
 *
 * A snapshot of the bridge's tools/list response (blender_mcp_bridge/tools/, get_mcp_tools())
 * for demo mode, where no real Blender is reachable to ask for a live list
 * (e.g. Studio deployed standalone on GitHub Pages). Powers the Add/Edit
 * Command schema-driven forms so they work identically in demo mode as they
 * do live; only the actual dispatch (lib/demoApi.js) is simulated, not the
 * tool catalog.
 *
 * Regenerated automatically by \`npm run dev\` / \`npm run build\`.
 */
export const DEMO_TOOLS = `;

// Emits the tool list as JSON on stdout. Kept inline (rather than as a
// committed .py) so there's no second file to keep in sync.
const PY = `
import json, sys
sys.path.insert(0, ${JSON.stringify(REPO_ROOT)})
from blender_mcp_bridge.tools import get_mcp_tools
print(json.dumps([
    {"name": t.name, "description": t.description, "inputSchema": t.inputSchema}
    for t in get_mcp_tools()
], indent=4))
`;

function dumpTools() {
    // uv is this project's toolchain (pyproject.toml/uv.lock); fall back to a
    // bare interpreter for environments that only have one of them.
    const attempts = [
        ['uv', ['run', 'python', '-c', PY]],
        ['python', ['-c', PY]],
        ['python3', ['-c', PY]],
    ];
    let lastErr = null;
    for (const [cmd, args] of attempts) {
        try {
            return execFileSync(cmd, args, {
                cwd: REPO_ROOT,
                encoding: 'utf-8',
                stdio: ['ignore', 'pipe', 'pipe'],
                maxBuffer: 32 * 1024 * 1024,
            });
        } catch (err) {
            lastErr = err;
        }
    }
    throw lastErr;
}

function main() {
    if (!existsSync(join(REPO_ROOT, 'blender_mcp_bridge', 'tools'))) {
        console.warn('[gen-demo-tools] blender_mcp_bridge/tools not found, keeping existing demoTools.js.');
        return;
    }

    let json;
    try {
        json = dumpTools();
    } catch (err) {
        console.warn(
            `[gen-demo-tools] could not run Python (${err.message.split('\n')[0]}), `
            + 'keeping existing demoTools.js.'
        );
        return;
    }

    let tools;
    try {
        tools = JSON.parse(json);
    } catch {
        console.warn('[gen-demo-tools] Python output was not valid JSON, keeping existing demoTools.js.');
        return;
    }
    if (!Array.isArray(tools) || tools.length === 0) {
        console.warn('[gen-demo-tools] got an empty tool list, keeping existing demoTools.js.');
        return;
    }

    const next = HEADER + JSON.stringify(tools, null, 4) + ';\n';
    const prev = existsSync(OUT_FILE) ? readFileSync(OUT_FILE, 'utf-8') : null;
    if (prev === next) {
        console.log(`[gen-demo-tools] ${tools.length} tools, already up to date.`);
        return;
    }
    writeFileSync(OUT_FILE, next);
    console.log(`[gen-demo-tools] wrote ${tools.length} tools to src/lib/demoTools.js`);
}

main();
